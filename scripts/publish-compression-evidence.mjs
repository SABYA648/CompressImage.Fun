import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const source = resolve('artifacts/benchmarks/exact-size.json');
const raw = JSON.parse(await readFile(source, 'utf8'));
if (!Array.isArray(raw) || raw.length === 0) {
  throw new Error('Run npm run benchmark:exact in Docker before publishing evidence.');
}

const noteFor = (row) => {
  if (!row.success) return 'No candidate fit under the cap at min quality 35.';
  const inputDimsUnknown = !row.inputWidth;
  if (row.outputBytes <= row.targetKB * 1024) {
    if (row.width && row.height && !inputDimsUnknown) {
      return 'At or below cap. Compare width/height to the source to see if the scale walk ran.';
    }
    return 'At or below cap. Quality search may have been enough, or dimensions changed.';
  }
  return 'Unexpected oversized result.';
};

const rows = raw.map((row) => ({
  fixture: row.fixture,
  license: 'Synthetic fixture generated by scripts/generate-fixtures.mjs (no third-party stock).',
  inputBytes: row.inputBytes,
  targetKB: row.targetKB,
  success: Boolean(row.success),
  outputBytes: row.outputBytes,
  width: row.width,
  height: row.height,
  quality: row.quality,
  iterations: row.iterations,
  elapsedMs: row.elapsedMs,
  note: noteFor(row),
}));

const generatedAt = new Date().toISOString();
const file = `export interface ExactSizeEvidenceRow {
  fixture: string;
  license: string;
  inputBytes: number;
  targetKB: number;
  success: boolean;
  outputBytes?: number;
  width?: number;
  height?: number;
  quality?: number;
  iterations?: number;
  elapsedMs?: number;
  note: string;
}

export interface CompressionEvidence {
  generatedAt: string;
  engine: string;
  settings: {
    minQuality: number;
    preserveMetadata: boolean;
    fixtures: string;
  };
  visualQualityLimitation: string;
  rows: ExactSizeEvidenceRow[];
}

export const compressionEvidence: CompressionEvidence = ${JSON.stringify(
  {
    generatedAt,
    engine: 'compressimage.fun exact-size optimizer (quality search, then dimension walk)',
    settings: {
      minQuality: 35,
      preserveMetadata: false,
      fixtures:
        'Deterministic synthetic photograph.jpg and illustration.png from scripts/generate-fixtures.mjs. Not third-party stock photos.',
    },
    visualQualityLimitation:
      'These rows report bytes, dimensions, quality, and search iterations. They do not score perceived quality. Synthetic fixtures are useful for regression, not as a claim about every camera JPEG.',
    rows,
  },
  null,
  2,
)};
`;

await writeFile(resolve('apps/web/src/data/compression-evidence.ts'), `${file}\n`);
console.log(`Published ${rows.length} evidence rows from ${source}`);
